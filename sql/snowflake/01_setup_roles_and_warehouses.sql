USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM;
CREATE OR REPLACE SCHEMA ENTERPRISE_INTELLIGENCE_PLATFORM.RAW;
CREATE OR REPLACE SCHEMA ENTERPRISE_INTELLIGENCE_PLATFORM.STAGING;
CREATE OR REPLACE SCHEMA ENTERPRISE_INTELLIGENCE_PLATFORM.CURATED;
CREATE OR REPLACE SCHEMA ENTERPRISE_INTELLIGENCE_PLATFORM.MART;
CREATE OR REPLACE SCHEMA ENTERPRISE_INTELLIGENCE_PLATFORM.SECURITY;
CREATE OR REPLACE SCHEMA ENTERPRISE_INTELLIGENCE_PLATFORM.MONITORING;

CREATE OR REPLACE WAREHOUSE EIP_ANALYTICS_WH
  WITH WAREHOUSE_SIZE = 'MEDIUM'
  AUTO_SUSPEND = 300
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE OR REPLACE WAREHOUSE EIP_ML_WH
  WITH WAREHOUSE_SIZE = 'LARGE'
  AUTO_SUSPEND = 300
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE OR REPLACE ROLE IF NOT EXISTS EIP_ADMIN;
CREATE OR REPLACE ROLE IF NOT EXISTS EIP_DATA_ENGINEER;
CREATE OR REPLACE ROLE IF NOT EXISTS EIP_ANALYST;
CREATE OR REPLACE ROLE IF NOT EXISTS EIP_SECURITY_ADMIN;
CREATE OR REPLACE ROLE IF NOT EXISTS EIP_ML_ENGINEER;

GRANT USAGE ON DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_ADMIN;
GRANT USAGE ON DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_DATA_ENGINEER;
GRANT USAGE ON DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_ANALYST;
GRANT USAGE ON DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_SECURITY_ADMIN;
GRANT USAGE ON DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_ML_ENGINEER;

GRANT USAGE ON ALL SCHEMAS IN DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_ADMIN;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_DATA_ENGINEER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_ANALYST;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_SECURITY_ADMIN;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ENTERPRISE_INTELLIGENCE_PLATFORM TO ROLE EIP_ML_ENGINEER;

GRANT USAGE ON WAREHOUSE EIP_ANALYTICS_WH TO ROLE EIP_ADMIN;
GRANT USAGE ON WAREHOUSE EIP_ANALYTICS_WH TO ROLE EIP_DATA_ENGINEER;
GRANT USAGE ON WAREHOUSE EIP_ANALYTICS_WH TO ROLE EIP_ANALYST;
GRANT USAGE ON WAREHOUSE EIP_ML_WH TO ROLE EIP_ML_ENGINEER;

CREATE OR REPLACE STAGE ENTERPRISE_INTELLIGENCE_PLATFORM.RAW.PROPERTY_LANDING
  FILE_FORMAT = (TYPE = 'CSV' FIELD_OPTIONALLY_ENCLOSED_BY = '"');

CREATE OR REPLACE STAGE ENTERPRISE_INTELLIGENCE_PLATFORM.RAW.API_LANDING
  FILE_FORMAT = (TYPE = 'JSON');

CREATE OR REPLACE STREAM ENTERPRISE_INTELLIGENCE_PLATFORM.RAW.PROPERTY_STREAM
  ON TABLE ENTERPRISE_INTELLIGENCE_PLATFORM.RAW.PROPERTY_LANDING;

